def migrate(admin_dsn, runtime_role):
    """Run explicitly with database-owner credentials, never during HTTP startup."""
    import psycopg
    from psycopg import sql

    if not re.fullmatch(r"[a-z_][a-z0-9_]{0,62}", runtime_role):
        raise ValueError("invalid runtime role")
    with psycopg.connect(admin_dsn) as db:
        db.execute(SCHEMA)
        db.execute(sql.SQL("GRANT USAGE ON SCHEMA public TO {}").format(sql.Identifier(runtime_role)))
        for table in ("projects", "records", "jobs", "events", "team_secrets", "team_projects"):
            db.execute(
                sql.SQL("GRANT SELECT,INSERT,UPDATE,DELETE ON {} TO {}").format(
                    sql.Identifier(table), sql.Identifier(runtime_role)
                )
            )
        for table in ("team_organizations", "team_members", "team_project_members", "team_queue"):
            db.execute(
                sql.SQL("GRANT SELECT ON {} TO {}").format(
                    sql.Identifier(table), sql.Identifier(runtime_role)
                )
            )
        db.execute(sql.SQL("GRANT INSERT ON team_queue TO {}").format(sql.Identifier(runtime_role)))
        db.execute(
            sql.SQL("GRANT USAGE,SELECT ON ALL SEQUENCES IN SCHEMA public TO {}").format(
                sql.Identifier(runtime_role)
            )
        )
        # Prevent caller supplied search_path/function replacement privilege escalation.
        db.execute("REVOKE CREATE ON SCHEMA public FROM PUBLIC")
        db.execute("REVOKE ALL ON ALL FUNCTIONS IN SCHEMA public FROM PUBLIC")
        for fn in (
            "team_subject()",
            "team_org()",
            "team_org_admin(text)",
            "team_permissions(text,text,text)",
            "team_can(text,text)",
            "team_memberships(text)",
            "team_lock_org(text)",
            "team_org_ledger(text)",
            "team_claim(text,text,integer)",
            "team_heartbeat(text,text,integer,boolean)",
            "team_release(text,text,boolean,integer)",
        ):
            db.execute(
                sql.SQL("GRANT EXECUTE ON FUNCTION " + fn + " TO {}").format(sql.Identifier(runtime_role))
            )


class _Connection:
    def __init__(self, db):
        self.db = db

    def execute(self, query, params=()):
        # Existing domain modules use the SQLite parameter spelling, not SQLite data.
        query = query.replace("?", "%s")
        if isinstance(params, dict):
            query = re.sub(r"(?<!:):([a-zA-Z_]\w*)", r"%(\1)s", query)
        return self.db.execute(query, params)


class PostgresStore(Store):
    def __init__(self, dsn):
        self.dsn = dsn
        with self._raw() as db:
            role = db.execute(
                "SELECT rolsuper,rolbypassrls FROM pg_roles WHERE rolname=current_user"
            ).fetchone()
            if role["rolsuper"] or role["rolbypassrls"]:
                raise ValueError("团队运行账户不得是 superuser 或 BYPASSRLS")
            if db.execute(
                "SELECT 1 FROM pg_class WHERE relname IN ('projects','records','jobs') AND relowner=(SELECT oid FROM pg_roles WHERE rolname=current_user)"
            ).fetchone():
                raise ValueError("团队运行账户不得拥有业务表")
            db.execute("SELECT 1 FROM team_queue LIMIT 0")

    @contextmanager
    def _raw(self):
        import psycopg
        from psycopg.rows import dict_row

        with psycopg.connect(self.dsn, row_factory=dict_row) as db:
            yield db

    @staticmethod
    def actor():
        actor = current_actor.get()
        if actor is None:
            raise PermissionError("团队操作缺少服务器身份范围")
        return actor

    @contextmanager
    def connection(self, write=False):
        actor = self.actor()
        if actor.worker:
            from .team_worker import active_lease

            lease = active_lease.get()
            if lease is not None and not self.heartbeat(lease[1]):
                raise Conflict("任务租约已丢失或成员权限已撤销")
        with self._raw() as db:
            db.execute(
                "SELECT set_config('creative.subject',%s,true),set_config('creative.organization',%s,true),set_config('creative.worker',%s,true)",
                (actor.subject, actor.organization_id, "true" if actor.worker else "false"),
            )
            db.execute(
                "SELECT set_config('creative.restore',%s,true)", ("true" if restore_mode.get() else "false",)
            )
            if write:
                db.execute("SELECT team_lock_org(%s)", (actor.organization_id,))
            yield _Connection(db)

    def memberships(self, subject):
        with self._raw() as db:
            return [
                r["organization_id"] for r in db.execute("SELECT * FROM team_memberships(%s)", (subject,))
            ]

    def require(self, project_id, *permissions):
        actor = self.actor()
        with self.connection() as db:
            row = db.execute(
                "SELECT team_permissions(?,?,?) AS permissions",
                (project_id, actor.subject, actor.organization_id),
            ).fetchone()
        grants = set(row["permissions"] or [])
        if not set(permissions) <= grants:
            raise PermissionError("当前成员缺少所需项目权限")
        return grants

    def require_org_admin(self):
        with self.connection() as db:
            if not db.execute("SELECT team_org_admin(?) AS ok", (self.actor().organization_id,)).fetchone()[
                "ok"
            ]:
                raise PermissionError("需要组织管理员权限")

    def create_project(self, name, budget=None, currency="CNY"):
        self.require_org_admin()
        if not name.strip() or len(name) > 100 or currency not in {"CNY", "USD"}:
            raise ValueError("项目名称或币种无效")
        if budget is not None and decimal(budget) < 0:
            raise ValueError("预算不能为负")
        data = {
            "id": uid(),
            "name": name.strip(),
            "budget": str(decimal(budget)) if budget is not None else None,
            "currency": currency,
            "created_at": now(),
        }
        with self.connection(True) as db:
            db.execute("INSERT INTO team_projects VALUES(?,?)", (data["id"], self.actor().organization_id))
            db.execute("INSERT INTO projects VALUES(:id,:name,:budget,:currency,:created_at)", data)
        return data

    def update_project(self, project_id, **kwargs):
        self.require(project_id, "budget")
        return super().update_project(project_id, **kwargs)

    def export_project(self, project_id):
        self.require(project_id, "export")
        return super().export_project(project_id)

    def _create_job(self, db, project_id, kind, payload, quote, idempotency_key):
        required = {"write"}
        if kind in {
            "analysis",
            "followup",
            "parse",
            "embedding",
            "scene_embedding",
            "search",
            "generation",
            "industry_search",
        }:
            required.add("external_model")
        if quote.amount is None:
            # Team deployments retain their independent organization-budget policy.
            self.require(project_id, 'paid')
            raise BudgetError('团队计费任务需要可核实的报价；个人本地版不要求填写单价')
        if quote.amount > 0:
            required.add("paid")
        self.require(project_id, *required)
        old = db.execute(
            "SELECT id FROM jobs WHERE project_id=? AND idempotency_key=?", (project_id, idempotency_key)
        ).fetchone()
        if not old:
            ledger = db.execute(
                "SELECT * FROM team_org_ledger(?)", (self.actor().organization_id,)
            ).fetchone()
            if not ledger or ledger["currency"] != quote.currency:
                raise BudgetError("组织和报价币种不一致")
            if quote.amount > 0 and (
                ledger["budget"] is None or ledger["used"] + quote.amount > ledger["budget"]
            ):
                raise BudgetError("组织预算不足；请先确认组织预算")
        job = super()._create_job(db, project_id, kind, payload, quote, idempotency_key)
        if not old:
            actor = self.actor()
            snapshot = dumps(
                {
                    "job_id": job["id"],
                    "kind": kind,
                    "payload": payload,
                    "quote": quote.model_dump(mode="json"),
                }
            )
            db.execute(
                "INSERT INTO team_queue(job_id,project_id,organization_id,actor_id,payer_id,required_permissions,snapshot) VALUES(?,?,?,?,?,?,?)",
                (
                    job["id"],
                    project_id,
                    actor.organization_id,
                    actor.subject,
                    actor.organization_id,
                    sorted(required),
                    snapshot,
                ),
            )
        return job

    def job_identity(self, project_id, job_id):
        self.job(project_id, job_id)
        with self.connection() as db:
            row = db.execute(
                "SELECT actor_id,payer_id,required_permissions,snapshot FROM team_queue WHERE job_id=?",
                (job_id,),
            ).fetchone()
        if not row:
            raise NotFound("团队任务身份快照不存在")
        return dict(row)

    def recover(self):
        # Recovery is lease based; API startup never modifies another worker's work.
        return None

    def pending_jobs(self):
        raise PermissionError("团队任务必须通过数据库租约领取")

    def claim(self, worker_id, lease_seconds=30):
        if not 5 <= lease_seconds <= 300:
            raise ValueError("租约时长必须为 5–300 秒")
        with self._raw() as db:
            row = db.execute(
                "SELECT * FROM team_claim(%s,%s,%s)", (worker_id, uid(), lease_seconds)
            ).fetchone()
        return dict(row) if row else None

    def heartbeat(self, claim, lease_seconds=30, complete=False):
        with self._raw() as db:
            return db.execute(
                "SELECT team_heartbeat(%s,%s,%s,%s) AS ok",
                (claim["job_id"], claim["lease_token"], lease_seconds, complete),
            ).fetchone()["ok"]

    def assert_lease(self, claim):
        if not self.heartbeat(claim):
            raise Conflict("任务租约已丢失或当前成员权限已撤销")
        self.require(claim["project_id"], *claim["required_permissions"])

    def release(self, claim, *, done, delay_seconds=10):
        with self._raw() as db:
            return db.execute(
                "SELECT team_release(%s,%s,%s,%s) AS ok",
                (claim["job_id"], claim["lease_token"], done, delay_seconds),
            ).fetchone()["ok"]

    def settle(self, project_id, job_id, actual_cost):
        self.require(project_id, "budget")
        return super().settle(project_id, job_id, actual_cost)

    def cancel(self, project_id, job_id):
        self.require(project_id, "write")
        job = self.job(project_id, job_id)
        if job["state"] == "queued":
            self.transition(project_id, job_id, "cancelled")
            # Releasing a never-submitted reservation is cancellation bookkeeping,
            # not a user-controlled correction to an actual supplier bill.
            return super().settle(project_id, job_id, "0")
        return super().cancel(project_id, job_id)

    def begin_cancel_attempt(self, project_id, job_id):
        from .team_worker import active_lease

        lease = active_lease.get()
        if lease is None or lease[1]["job_id"] != job_id:
            raise PermissionError("供应商取消必须持有当前任务租约")
        self.assert_lease(lease[1])
        with self.connection(True) as db:
            row = db.execute(
                "SELECT state,provider_request_id FROM jobs WHERE project_id=? AND id=?", (project_id, job_id)
            ).fetchone()
            if not row or row["state"] != "cancelling" or not row["provider_request_id"]:
                raise Conflict("任务尚无可取消的已提交编号")
            if db.execute(
                "SELECT 1 FROM events WHERE job_id=? AND type='cancel_attempt' LIMIT 1", (job_id,)
            ).fetchone():
                return False
            db.execute(
                "INSERT INTO events(job_id,type,data,created_at) VALUES(?,?,?,?)",
                (
                    job_id,
                    "cancel_attempt",
                    dumps(
                        {
                            "provider_request_id": row["provider_request_id"],
                            "outcome": "unknown_until_confirmed",
                        }
                    ),
                    now(),
                ),
            )
        return True

    def restore_record(self, project_id, kind, data, record_id):
        # Historical approvals are retained as history during the explicit,
        # administrator-only bundle import. This flag is never taken from HTTP.
        self.require_org_admin()
        token = restore_mode.set(True)
        try:
            return super().restore_record(project_id, kind, data, record_id)
        finally:
            restore_mode.reset(token)
